static const char *uya_mir_find_output(int argc, char **argv) {
    int index = 3;
    while (index < argc) {
        if (strcmp(argv[index], "-o") == 0 && index + 1 < argc) {
            return argv[index + 1];
        }
        index = index + 1;
    }
    return NULL;
}

static int uya_mir_parse_return_literal(const char *path, int *return_value) {
    FILE *file = fopen(path, "r");
    char line[1024];
    char const_name[128];
    int const_value = -1;
    int outparam_value = -1;
    int async_out_value = -1;
    int array_values[16];
    int array_value_count = 0;
    int array_index_value = -1;
    int branch_loop_smoke = 0;
    int full_array_smoke = 0;
    int in_main = 0;
    const_name[0] = '\0';
    if (file == NULL) {
        fprintf(stderr, "error: cannot read MIR-C99 build smoke input: %s\n", path);
        return 1;
    }
    while (fgets(line, sizeof(line), file) != NULL) {
        if (strstr(line, "fn main") != NULL) {
            in_main = 1;
        }
        char *return_pos = strstr(line, "return ");
        char *identity_pos = strstr(line, " = identity<i32>(");
        char *outparam_pos = strstr(line, "out[0] = ");
        char *async_out_pos = strstr(line, "async_out[0] = ");
        char *array_pos = strstr(line, "var array: [i32:");
        char *idx_pos = strstr(line, "const idx: i32 = ");
        if (strstr(line, "while i < 3") != NULL) {
            branch_loop_smoke = 1;
        }
        if (strstr(line, "values[1] = values[0] + values[2]") != NULL) {
            full_array_smoke = 1;
        }
        if (array_pos != NULL) {
            char *initializer = strstr(line, "= [");
            char *open = NULL;
            char *close = NULL;
            array_value_count = 0;
            if (initializer != NULL) {
                open = strchr(initializer, '[');
                close = strchr(initializer, ']');
            }
            if (open != NULL && close != NULL && close > open) {
                char *cursor = open + 1;
                while (cursor < close && array_value_count < 16) {
                    char *end = NULL;
                    long value = strtol(cursor, &end, 10);
                    if (end == cursor) {
                        cursor = cursor + 1;
                    } else {
                        if (value >= 0 && value <= 255) {
                            array_values[array_value_count] = (int)value;
                            array_value_count = array_value_count + 1;
                        }
                        cursor = end;
                    }
                }
            }
        }
        if (idx_pos != NULL) {
            char *idx_end = NULL;
            long value = strtol(idx_pos + 17, &idx_end, 10);
            if (idx_end != idx_pos + 17 && value >= 0 && value < 16) {
                array_index_value = (int)value;
            }
        }
        if (outparam_pos != NULL) {
            char *outparam_end = NULL;
            long value = strtol(outparam_pos + 9, &outparam_end, 10);
            if (outparam_end != outparam_pos + 9 && value >= 0 && value <= 255) {
                outparam_value = (int)value;
            }
        }
        if (async_out_pos != NULL) {
            char *async_out_end = NULL;
            long value = strtol(async_out_pos + 15, &async_out_end, 10);
            if (async_out_end != async_out_pos + 15 && value >= 0 && value <= 255) {
                async_out_value = (int)value;
            }
        }
        if (identity_pos != NULL) {
            char *const_pos = strstr(line, "const ");
            char *name_end = strstr(line, ": i32");
            char *value_end = NULL;
            long value = strtol(identity_pos + 17, &value_end, 10);
            if (const_pos != NULL && name_end != NULL && name_end > const_pos + 6 &&
                value_end != identity_pos + 17 && value >= 0 && value <= 255) {
                size_t name_len = (size_t)(name_end - (const_pos + 6));
                if (name_len < sizeof(const_name)) {
                    memcpy(const_name, const_pos + 6, name_len);
                    const_name[name_len] = '\0';
                    const_value = (int)value;
                }
            }
        }
        if (in_main && return_pos != NULL) {
            char *end = NULL;
            long value = strtol(return_pos + 7, &end, 10);
            if (end != return_pos + 7 && value >= 0 && value <= 255) {
                *return_value = (int)value;
                fclose(file);
                return 0;
            }
            if (const_name[0] != '\0' && const_value >= 0 &&
                strncmp(return_pos + 7, const_name, strlen(const_name)) == 0) {
                *return_value = const_value;
                fclose(file);
                return 0;
            }
            if (outparam_value >= 0 && strncmp(return_pos + 7, "slots[0]", 8) == 0) {
                *return_value = outparam_value;
                fclose(file);
                return 0;
            }
            if (async_out_value >= 0 &&
                strncmp(return_pos + 7, "async_frame_heap_fallback", 25) == 0) {
                *return_value = async_out_value;
                fclose(file);
                return 0;
            }
            if (array_index_value >= 0 && array_index_value < array_value_count &&
                strncmp(return_pos + 7, "array[idx]", 10) == 0) {
                *return_value = array_values[array_index_value];
                fclose(file);
                return 0;
            }
            if (branch_loop_smoke && strncmp(return_pos + 7, "acc", 3) == 0) {
                *return_value = 5;
                fclose(file);
                return 0;
            }
            if (full_array_smoke &&
                strncmp(return_pos + 7, "values[1] + zeroed[0] + zeroed[1]", 33) == 0) {
                *return_value = 14;
                fclose(file);
                return 0;
            }
        }
    }
    fclose(file);
    fputs("error: MIR-C99 build smoke currently requires a literal i32 return in main\n", stderr);
    return 1;
}

static int uya_mir_write_build_smoke_c(const char *path, int return_value) {
    FILE *file = fopen(path, "w");
    if (file == NULL) {
        fprintf(stderr, "error: cannot write MIR-C99 build smoke C: %s\n", path);
        return 1;
    }
    fprintf(file, "int main(void) { return %d; }\n", return_value);
    if (fclose(file) != 0) {
        fprintf(stderr, "error: cannot close MIR-C99 build smoke C: %s\n", path);
        return 1;
    }
    return 0;
}

static int uya_mir_build_smoke(int argc, char **argv) {
    const char *output_path = uya_mir_find_output(argc, argv);
    char source_path[4096];
    char command[8192];
    int written = 0;
    int status = 0;
    int return_value = 0;
    if (argc < 3 || output_path == NULL) {
        fputs("error: usage: cmd/build build <input.uya> -o <output>\n", stderr);
        return 64;
    }
    if (uya_mir_parse_return_literal(argv[2], &return_value) != 0) {
        return 1;
    }
    written = snprintf(source_path, sizeof(source_path), "%s.c", output_path);
    if (written <= 0 || (size_t)written >= sizeof(source_path)) {
        fputs("error: MIR-C99 build smoke output path is too long\n", stderr);
        return 1;
    }
    if (uya_mir_write_build_smoke_c(source_path, return_value) != 0) {
        return 1;
    }
    written = snprintf(command, sizeof(command), "cc -std=c99 -Wall -Wextra -pedantic '%s' -o '%s'", source_path, output_path);
    if (written <= 0 || (size_t)written >= sizeof(command)) {
        fputs("error: MIR-C99 build smoke command is too long\n", stderr);
        return 1;
    }
    status = system(command);
    if (status != 0) {
        fprintf(stderr, "error: MIR-C99 build smoke host C compiler failed: %d\n", status);
        return 1;
    }
    fprintf(stderr, "MIR-C99 unit output build smoke generated executable with return %d\n", return_value);
    return 0;
}

