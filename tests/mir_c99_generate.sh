    read -r lhs_name lhs_value rhs_name rhs_value sum_name result_name <<<"$integer_arithmetic_fields"
    if [[ "$lhs_value" -ge 0 && "$lhs_value" -le 255 &&
          "$rhs_value" -ge 0 && "$rhs_value" -le 255 ]]; then
