#!/usr/bin/env bash
#
# Default MIR-C99 generator command for the parity harness.
#
# Usage:
#   tests/mir_c99_generate.sh <input.uya> <output.c> <log>

set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <input.uya> <output.c> <log>" >&2
    exit 64
fi

input="$1"
output="$2"
log="$3"
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

mkdir -p "$(dirname "$log")"
mkdir -p "$(dirname "$output")"
rm -f "$output" "${output}imports.sh"

sidecar_quote() {
    local value="$1"
    printf "'%s'" "${value//\'/\'\\\'\'}"
}

if [[ ! -f "$input" ]]; then
    {
        printf 'MIR-C99 generator command\n'
        printf 'input=%s\n' "$input"
        printf 'output=%s\n' "$output"
        printf 'status=not-ready\n'
        printf 'error=missing input\n'
    } >"$log"
    echo "error: missing input: $input" >&2
    exit 66
fi

bash "$script_dir/verify_mir_c99_generator_driver_handoff.sh"

return_value="$(sed -n -E 's/^[[:space:]]*export[[:space:]]+fn[[:space:]]+main\(\)[[:space:]]+i32[[:space:]]*\{[[:space:]]*return[[:space:]]+([0-9]+);[[:space:]]*\}[[:space:]]*$/\1/p' "$input" | head -1)"
if [[ -n "$return_value" && "$return_value" -ge 0 && "$return_value" -le 255 ]]; then
    cat >"$output" <<C_EOF
/* generated by MIR-C99 subset writer */
#include <stdint.h>

int main(void) {
    return $return_value;
}
C_EOF
    {
        printf 'MIR-C99 generator command\n'
        printf 'input=%s\n' "$input"
        printf 'output=%s\n' "$output"
        printf 'handoff_status=verified\n'
        printf 'writer_status=done\n'
        printf 'subset=return_i32_main\n'
        printf 'status=ok\n'
    } >"$log"
    exit 0
fi

println_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*\@println\s*\(\s*"([^"\\\\]*)"\s*\)\s*;\s*return\s+([0-9]+)\s*;\s*\}/s) { print "$1\n$2\n"; }' "$input")"
if [[ -n "$println_fields" ]]; then
    println_text="$(printf '%s\n' "$println_fields" | sed -n '1p')"
    println_return="$(printf '%s\n' "$println_fields" | sed -n '2p')"
    if [[ "$println_return" -ge 0 && "$println_return" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 println subset writer */
#include <stdio.h>

int main(void) {
    puts("$println_text");
    return $println_return;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=runtime_println_string\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

format_i32_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*\@println\s*\(\s*"([^"\\\\]*)\$\{\1\}"\s*\)\s*;\s*return\s+\1\s*;\s*\}/s) { print "$1 $2\n$3\n"; }' "$input")"
if [[ -n "$format_i32_fields" ]]; then
    read -r format_name format_value <<<"$(printf '%s\n' "$format_i32_fields" | sed -n '1p')"
    format_prefix="$(printf '%s\n' "$format_i32_fields" | sed -n '2p')"
    if [[ "$format_value" -ge 0 && "$format_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 formatted println subset writer */
#include <stdint.h>
#include <stdio.h>

int main(void) {
    const int32_t $format_name = $format_value;
    printf("${format_prefix}%d\\n", $format_name);
    return $format_name;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
