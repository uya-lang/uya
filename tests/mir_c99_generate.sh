    const char *msg = "$file_msg";
    const int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd < 0) {
        return $open_error;
    }
    const ssize_t written = write(fd, msg, (size_t)$write_count);
    if (written < 0) {
        (void)close(fd);
        return $write_error;
    }
    if (close(fd) != 0) {
        return $close_error;
    }
    if (unlink(path) != 0) {
        return $unlink_error;
    }
    return (int32_t)written;
