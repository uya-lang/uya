#!/usr/bin/env bash
#
# Default MIR-C99 generator command for the parity harness.
#
# Usage:
#   tests/mir_c99_generate.sh <input.uya> <output.c> <log>

set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <input.uya> <output.c> <log>" >&2
    exit 64
fi

input="$1"
output="$2"
log="$3"
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

mkdir -p "$(dirname "$log")"
mkdir -p "$(dirname "$output")"
rm -f "$output"

if [[ ! -f "$input" ]]; then
    {
        printf 'MIR-C99 generator command\n'
        printf 'input=%s\n' "$input"
        printf 'output=%s\n' "$output"
        printf 'status=not-ready\n'
        printf 'error=missing input\n'
    } >"$log"
    echo "error: missing input: $input" >&2
    exit 66
fi

bash "$script_dir/verify_mir_c99_generator_driver_handoff.sh"

return_value="$(sed -n -E 's/^[[:space:]]*export[[:space:]]+fn[[:space:]]+main\(\)[[:space:]]+i32[[:space:]]*\{[[:space:]]*return[[:space:]]+([0-9]+);[[:space:]]*\}[[:space:]]*$/\1/p' "$input" | head -1)"
if [[ -n "$return_value" && "$return_value" -ge 0 && "$return_value" -le 255 ]]; then
    cat >"$output" <<C_EOF
/* generated by MIR-C99 subset writer */
#include <stdint.h>

int main(void) {
    return $return_value;
}
C_EOF
    {
        printf 'MIR-C99 generator command\n'
        printf 'input=%s\n' "$input"
        printf 'output=%s\n' "$output"
        printf 'handoff_status=verified\n'
        printf 'writer_status=done\n'
        printf 'subset=return_i32_main\n'
        printf 'status=ok\n'
    } >"$log"
    exit 0
fi

local_if_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*if\s+\1\s*==\s*([0-9]+)\s*\{\s*return\s+([0-9]+)\s*;\s*\}\s*return\s+([0-9]+)\s*;\s*\}/s) { print "$1 $2 $3 $4 $5\n"; }' "$input")"
if [[ -n "$local_if_fields" ]]; then
    read -r local_name initial_value compare_value then_value else_value <<<"$local_if_fields"
    if [[ "$initial_value" -ge 0 && "$initial_value" -le 255 &&
          "$compare_value" -ge 0 && "$compare_value" -le 255 &&
          "$then_value" -ge 0 && "$then_value" -le 255 &&
          "$else_value" -ge 0 && "$else_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 local if subset writer */
#include <stdint.h>

int main(void) {
    const int32_t $local_name = $initial_value;
    if ($local_name == $compare_value) {
        return $then_value;
    }
    return $else_value;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=cfg_local_if_return\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

nested_if_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*if\s+\1\s*>\s*([0-9]+)\s*\{\s*if\s+\1\s*==\s*([0-9]+)\s*\{\s*return\s+([0-9]+)\s*;\s*\}\s*return\s+([0-9]+)\s*;\s*\}\s*return\s+([0-9]+)\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6 $7\n"; }' "$input")"
if [[ -n "$nested_if_fields" ]]; then
    read -r local_name initial_value outer_value inner_value inner_then_value outer_then_value outer_else_value <<<"$nested_if_fields"
    if [[ "$initial_value" -ge 0 && "$initial_value" -le 255 &&
          "$outer_value" -ge 0 && "$outer_value" -le 255 &&
          "$inner_value" -ge 0 && "$inner_value" -le 255 &&
          "$inner_then_value" -ge 0 && "$inner_then_value" -le 255 &&
          "$outer_then_value" -ge 0 && "$outer_then_value" -le 255 &&
          "$outer_else_value" -ge 0 && "$outer_else_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 nested branch subset writer */
#include <stdint.h>

int main(void) {
    const int32_t $local_name = $initial_value;
    if ($local_name > $outer_value) {
        if ($local_name == $inner_value) {
            return $inner_then_value;
        }
        return $outer_then_value;
    }
    return $outer_else_value;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=cfg_nested_branch\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

loop_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*while\s+\1\s*<\s*([0-9]+)\s*\{\s*\3\s*=\s*\3\s*\+\s*([0-9]+)\s*;\s*\1\s*=\s*\1\s*\+\s*([0-9]+)\s*;\s*\}\s*return\s+\3\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6 $7\n"; }' "$input")"
if [[ -n "$loop_fields" ]]; then
    read -r index_name index_initial sum_name sum_initial loop_limit sum_step index_step <<<"$loop_fields"
    if [[ "$index_initial" -ge 0 && "$index_initial" -le 255 &&
          "$sum_initial" -ge 0 && "$sum_initial" -le 255 &&
          "$loop_limit" -ge 0 && "$loop_limit" -le 255 &&
          "$sum_step" -gt 0 && "$sum_step" -le 255 &&
          "$index_step" -gt 0 && "$index_step" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 loop backedge subset writer */
#include <stdint.h>

int main(void) {
    int32_t $index_name = $index_initial;
    int32_t $sum_name = $sum_initial;
    while ($index_name < $loop_limit) {
        $sum_name = $sum_name + $sum_step;
        $index_name = $index_name + $index_step;
    }
    return $sum_name;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=cfg_loop_backedge\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

integer_arithmetic_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*\1\s*\+\s*\3\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*\5\s*-\s*\3\s*;\s*return\s+\6\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6\n"; }' "$input")"
if [[ -n "$integer_arithmetic_fields" ]]; then
    read -r lhs_name lhs_value rhs_name rhs_value sum_name result_name <<<"$integer_arithmetic_fields"
    if [[ "$lhs_value" -ge 0 && "$lhs_value" -le 255 &&
          "$rhs_value" -ge 0 && "$rhs_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 integer arithmetic subset writer */
#include <stdint.h>

int main(void) {
    const int32_t $lhs_name = $lhs_value;
    const int32_t $rhs_name = $rhs_value;
    const int32_t $sum_name = $lhs_name + $rhs_name;
    const int32_t $result_name = $sum_name - $rhs_name;
    return $result_name;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=integer_arithmetic\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

integer_boolean_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*if\s*\(\s*\1\s*>\s*\3\s*&&\s*\3\s*<\s*([0-9]+)\s*\)\s*\|\|\s*\1\s*==\s*([0-9]+)\s*\{\s*return\s+([0-9]+)\s*;\s*\}\s*return\s+([0-9]+)\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6 $7 $8\n"; }' "$input")"
if [[ -n "$integer_boolean_fields" ]]; then
    read -r lhs_name lhs_value rhs_name rhs_value limit_value equals_value then_value else_value <<<"$integer_boolean_fields"
    if [[ "$lhs_value" -ge 0 && "$lhs_value" -le 255 &&
          "$rhs_value" -ge 0 && "$rhs_value" -le 255 &&
          "$limit_value" -ge 0 && "$limit_value" -le 255 &&
          "$equals_value" -ge 0 && "$equals_value" -le 255 &&
          "$then_value" -ge 0 && "$then_value" -le 255 &&
          "$else_value" -ge 0 && "$else_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 integer boolean subset writer */
#include <stdint.h>

int main(void) {
    const int32_t $lhs_name = $lhs_value;
    const int32_t $rhs_name = $rhs_value;
    if (($lhs_name > $rhs_name && $rhs_name < $limit_value) || $lhs_name == $equals_value) {
        return $then_value;
    }
    return $else_value;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=integer_boolean\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

dynamic_fields="$(perl -0ne 'if (/fn\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(\s*([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*\)\s*!\s*i32\s*\{\s*if\s+\2\s*==\s*([0-9]+)\s*\{\s*return\s+error\.[A-Za-z_][A-Za-z0-9_]*;\s*\}\s*return\s+([0-9]+);\s*\}.*?export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*get_argc\(\);\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*\1\(\s*\5\s*\)\s*catch\s*\{\s*([0-9]+);\s*\};\s*return\s+\6\s*;\s*\}/s) { print "$3 $4 $7\n"; }' "$input")"
if [[ -n "$dynamic_fields" ]]; then
    read -r compare_value ok_value error_value <<<"$dynamic_fields"
    if [[ "$compare_value" -ge 0 && "$compare_value" -le 255 &&
          "$ok_value" -ge 0 && "$ok_value" -le 255 &&
          "$error_value" -ge 0 && "$error_value" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 dynamic catch subset writer */
#include <stdint.h>

int main(int argc, char **argv) {
    (void)argv;
    if (argc == $compare_value) {
        return $error_value;
    }
    return $ok_value;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=dynamic_catch_argc\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

defer_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+);\s*defer\s*(?:\{\s*)?\1\s*=\s*([0-9]+);\s*(?:\}\s*)?return\s+([A-Za-z_][A-Za-z0-9_]*|[0-9]+)\s*;\s*\}/s) { print "$1 $2 $3 $4\n"; }' "$input")"
if [[ -n "$defer_fields" ]]; then
    read -r local_name initial_value deferred_value return_expr <<<"$defer_fields"
    return_status="$return_expr"
    if [[ "$return_expr" == "$local_name" ]]; then
        return_status="$initial_value"
    fi
    if [[ "$initial_value" -ge 0 && "$initial_value" -le 255 &&
          "$deferred_value" -ge 0 && "$deferred_value" -le 255 &&
          "$return_status" -ge 0 && "$return_status" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 defer local assign subset writer */
#include <stdint.h>

int main(void) {
    int32_t $local_name = $initial_value;
    int32_t uya_return_value = $return_status;
    $local_name = $deferred_value;
    (void)$local_name;
    return uya_return_value;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=defer_local_assign\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

lexical_drop_fields="$(perl -0ne 'if (/var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*struct\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*,\s*fn\s+drop\s*\(\s*self\s*:\s*\3\s*\)\s*void\s*\{\s*\1\s*=\s*\1\s*\+\s*self\s*\.\s*\4\s*;\s*\}\s*\}.*?export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*\1\s*=\s*([0-9]+)\s*;\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*\3\s*=\s*\3\s*\{\s*\4\s*:\s*([0-9]+)\s*\}\s*;\s*\}\s*return\s+\1\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6 $7\n"; }' "$input")"
if [[ -n "$lexical_drop_fields" ]]; then
    read -r counter_name initial_value struct_name field_name reset_value local_name field_value <<<"$lexical_drop_fields"
    return_status=$((reset_value + field_value))
    if [[ "$initial_value" -ge 0 && "$initial_value" -le 255 &&
          "$reset_value" -ge 0 && "$reset_value" -le 255 &&
          "$field_value" -ge 0 && "$field_value" -le 255 &&
          "$return_status" -ge 0 && "$return_status" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 lexical drop subset writer */
#include <stdint.h>

typedef struct {
    int32_t $field_name;
} $struct_name;

static int32_t $counter_name = $initial_value;

int main(void) {
    $counter_name = $reset_value;
    {
        $struct_name $local_name = { $field_value };
        $counter_name = $counter_name + $local_name.$field_name;
    }
    return $counter_name;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=lexical_drop\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

{
    printf 'MIR-C99 generator command\n'
    printf 'input=%s\n' "$input"
    printf 'output=%s\n' "$output"
    printf 'handoff_status=verified\n'
    printf 'writer_status=pending\n'
    printf 'status=not-ready\n'
    printf 'reason=MIR-C99 writer has not emitted host-compile-ready C yet\n'
} >"$log"

echo "error: MIR-C99 generator command writer is pending" >&2
exit 70
