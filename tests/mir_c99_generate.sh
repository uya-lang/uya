static void async_frame_pool_init_with_buffer(MirAsyncFramePool *pool,
    uint8_t *buffer, size_t buffer_size, int32_t debug_heap_fallback,
    size_t stack_limit) {
    pool->buffer = buffer;
    pool->buffer_size = buffer_size;
    pool->buffer_used = 0;
