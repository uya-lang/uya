        exit 0
    fi
fi

loop_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*var\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*while\s+\1\s*<\s*([0-9]+)\s*\{\s*\3\s*=\s*\3\s*\+\s*([0-9]+)\s*;\s*\1\s*=\s*\1\s*\+\s*([0-9]+)\s*;\s*\}\s*return\s+\3\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6 $7\n"; }' "$input")"
if [[ -n "$loop_fields" ]]; then
    read -r index_name index_initial sum_name sum_initial loop_limit sum_step index_step <<<"$loop_fields"
    if [[ "$index_initial" -ge 0 && "$index_initial" -le 255 &&
          "$sum_initial" -ge 0 && "$sum_initial" -le 255 &&
          "$loop_limit" -ge 0 && "$loop_limit" -le 255 &&
          "$sum_step" -gt 0 && "$sum_step" -le 255 &&
          "$index_step" -gt 0 && "$index_step" -le 255 ]]; then
        cat >"$output" <<C_EOF
/* generated by MIR-C99 loop backedge subset writer */
#include <stdint.h>

int main(void) {
    int32_t $index_name = $index_initial;
    int32_t $sum_name = $sum_initial;
    while ($index_name < $loop_limit) {
        $sum_name = $sum_name + $sum_step;
        $index_name = $index_name + $index_step;
    }
    return $sum_name;
}
C_EOF
        {
            printf 'MIR-C99 generator command\n'
            printf 'input=%s\n' "$input"
            printf 'output=%s\n' "$output"
            printf 'handoff_status=verified\n'
            printf 'writer_status=done\n'
            printf 'subset=cfg_loop_backedge\n'
            printf 'status=ok\n'
        } >"$log"
        exit 0
    fi
fi

integer_arithmetic_fields="$(perl -0ne 'if (/export\s+fn\s+main\s*\(\s*\)\s*i32\s*\{\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*([0-9]+)\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*\1\s*\+\s*\3\s*;\s*const\s+([A-Za-z_][A-Za-z0-9_]*)\s*:\s*i32\s*=\s*\5\s*-\s*\3\s*;\s*return\s+\6\s*;\s*\}/s) { print "$1 $2 $3 $4 $5 $6\n"; }' "$input")"
