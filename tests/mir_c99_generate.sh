if [[ -n "$println_fields" ]]; then
    println_text="$(printf '%s\n' "$println_fields" | sed -n '1p')"
    println_return="$(printf '%s\n' "$println_fields" | sed -n '2p')"
    if [[ "$println_return" -ge 0 && "$println_return" -le 255 ]]; then
        cat >"$output" <<C_EOF
