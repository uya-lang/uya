static int ptr_in_range(uint8_t *base, size_t size, uint8_t *ptr) {
    return base != NULL && ptr != NULL && ptr >= base && ptr < base + size;
}

static uint8_t *async_frame_pool_alloc_aligned(MirAsyncFramePool *pool,
    size_t size, size_t align) {
    size_t aligned = pool->buffer_used;
    if (align > 0 && (aligned % align) != 0) {
        aligned += align - (aligned % align);
    }
    if (size <= pool->stack_limit && aligned + size <= pool->buffer_size) {
        pool->buffer_used = aligned + size;
        pool->total_alloc += 1;
        return pool->buffer + aligned;
    }
    pool->full_count += 1;
    if (!pool->debug_heap_fallback) {
        return NULL;
    }
    pool->heap_fallback += 1;
    pool->total_alloc += 1;
    return (uint8_t *)malloc(size);
}

static void async_frame_pool_free_aligned(MirAsyncFramePool *pool,
    uint8_t *ptr, size_t size, size_t align) {
    (void)size;
    (void)align;
    if (ptr == NULL) {
        return;
    }
    if (!ptr_in_range(pool->buffer, pool->buffer_size, ptr)) {
        free(ptr);
    }
    pool->total_free += 1;
}

int main(void) {
    uint8_t storage[256] = { 0 };
    MirAsyncFramePool pool;
    async_frame_pool_init_with_buffer(&pool, storage, 256u, 1, 64u);
    uint8_t *small_ptr = async_frame_pool_alloc_aligned(&pool, 32u, 8u);
    if (small_ptr == NULL || !ptr_in_range(storage, 256u, small_ptr)) {
        return 2;
    }
    uint8_t *large_ptr = async_frame_pool_alloc_aligned(&pool, 96u, 8u);
    if (large_ptr == NULL || ptr_in_range(storage, 256u, large_ptr)) {
        return 3;
    }
    async_frame_pool_free_aligned(&pool, small_ptr, 32u, 8u);
    async_frame_pool_free_aligned(&pool, large_ptr, 96u, 8u);
    if (pool.total_alloc < 1 || pool.total_free < 1 || pool.heap_fallback < 1) {
        return 4;
    }
    return 9;
}
